@dataclass
class SenderSpec:
    addr: str
    name: str
    weight: int                       # messages per 45k mailbox
    gmail_cat: str                    # Gmail tab label
    subjects: list[str]
    snippet: str
    list_id: str | None = None
    one_click: bool = True
    unread: float = 0.9
    starred: float = 0.002
    # (fraction, subjects, snippet): transactional mail mixed into an otherwise disposable sender
    exceptions: list[tuple[float, list[str], str]] = field(default_factory=list)


def _s(*a, **k) -> SenderSpec:
    return SenderSpec(*a, **k)


